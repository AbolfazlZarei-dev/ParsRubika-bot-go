// Photo matches messages that have a photo attachment (file_inline of
// type "Image").
type Photo struct{}

// Check implements Rule.
func (Photo) Check(_ context.Context, upd *models.Update) bool {
	if upd.NewMessage != nil && upd.NewMessage.File != nil {
		// Bot API doesn't expose a `type` field on File; the caller
		// can use the file_name's extension as a hint. As a basic
		// heuristic, any file with a known image extension is treated
		// as a photo. See PhotoByExtension for an explicit version.
		return isImageExt(upd.NewMessage.File.FileName)
	}
	return false
}

// PhotoByExtension matches messages whose file attachment has one of
// the supplied extensions.
type PhotoByExtension struct{ Exts []string }

// Check implements Rule.
func (p PhotoByExtension) Check(_ context.Context, upd *models.Update) bool {
	if upd.NewMessage == nil || upd.NewMessage.File == nil {
		return false
	}
	return hasExt(upd.NewMessage.File.FileName, p.Exts)
}

