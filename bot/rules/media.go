// SenderType matches by the `sender_type` field (`User`, `Bot`,
// `Group`, `Channel`).
type SenderType struct{ Types []string }

// NewSenderType constructs a SenderType rule.
func NewSenderType(types ...string) *SenderType { return &SenderType{Types: types} }

// Check implements Rule.
func (s SenderType) Check(_ context.Context, upd *models.Update) bool {
	st := ""
	if upd.NewMessage != nil {
		st = upd.NewMessage.SenderType
	} else if upd.UpdatedMessage != nil {
		st = upd.UpdatedMessage.SenderType
	}
	for _, want := range s.Types {
		if st == want {
			return true
		}
	}
	return false
}

