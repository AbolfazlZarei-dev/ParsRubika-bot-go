// ===== small helpers ==================================================

func isImageExt(name string) bool {
	return hasExt(name, []string{".jpg", ".jpeg", ".png", ".webp", ".gif"})
}

func isVoiceExt(name string) bool {
	return hasExt(name, []string{".ogg", ".opus"})
}

func isVideoExt(name string) bool {
	return hasExt(name, []string{".mp4", ".mkv", ".webm", ".mov", ".avi"})
}

func isAudioExt(name string) bool {
	return hasExt(name, []string{".mp3", ".m4a", ".aac", ".flac", ".wav", ".ogg"})
}

func hasExt(name string, exts []string) bool {
	if name == "" {
		return false
	}
	low := toLower(name)
	for _, ext := range exts {
		if endsWith(low, ext) {
			return true
		}
	}
	return false
}

func toLower(s string) string {
	out := make([]byte, len(s))
	for i, c := range []byte(s) {
		if c >= 'A' && c <= 'Z' {
			out[i] = c + 32
		} else {
			out[i] = c
		}
	}
	return string(out)
}

func endsWith(s, suffix string) bool {
	if len(suffix) > len(s) {
		return false
	}
	return s[len(s)-len(suffix):] == suffix
}
